for i in ["T4b", "T6b", "S17", "D-1S", "P-NA", "C11", "R-FS", "WS1", "WS2", "WS3"]: MAP[i + " "] = [i]
def ids_for(name):
    name = name[len("golden:"):] if name.startswith("golden:") else name
    return [i for k, v in MAP.items() if name.startswith(k) for i in v]
def tagify(i): return "[" + i.replace("/", "_") + "]"
def tag():
    for f in ("tests/test_core.cpp", "tests/test_golden.cpp"):
        p = os.path.join(ROOT, f); s = open(p).read()
        def sub(m):
            name, rest = m.group(1), m.group(2) or ""
            ids = ids_for(name)
            if not ids or "[PartA]" in rest: return m.group(0)
            tags = "[PartA]" + "".join(dict.fromkeys(tagify(i) for i in ids))
            if rest: return f'TEST_CASE("{name}", "{tags}{rest[3:-1]}")' if False else f'TEST_CASE("{name}", "{tags}' + rest[rest.index('"') + 1:]
            return f'TEST_CASE("{name}", "{tags}")'
        s = re.sub(r'TEST_CASE\("([^"]+)"(, "[^"]*"\))?\)?', lambda m: sub(m) if m.group(2) is None else sub(m), s)
        open(p, "w").write(s)
def doc(junits):
    res = {}
    for j in junits:
        for tc in ET.parse(j).getroot().iter("testcase"):
            n = tc.get("name"); st = "pass"
            if tc.find("skipped") is not None: st = "skipped"
            elif tc.find("failure") is not None or tc.find("error") is not None: st = "FAIL"
            res[n] = st
    rows = []
    for i in IDS:
        tests = [n for n in sorted(set(list(res) + [k for k in MAP])) if i in ids_for(n) and (n in res or not res)]
        names = sorted({n for n in res if i in ids_for(n)}) if res else sorted(k for k, v in MAP.items() if i in v)
        sts = [res.get(n, "?") for n in names]
        xf = any("shouldfail" in n for n in names)
        if not names: status = "not covered"
        elif all(s == "skipped" for s in sts): status = "skipped (placeholder)"
        elif i == "D-SGN": status = "xfail (unbuilt: negative lags); golden swap check passes"
        elif "FAIL" in sts: status = "FAIL"
        else: status = "pass"
        rows.append((i, "; ".join(names) or "-", status))
    out = ["# Part A coverage map", "", "Source: `docs/qa/test-checklist-build1.md` Part A (70 IDs, incl. D-ERR). Generated by `tools/part_a_map.py doc <junit.xml>` from a ctest run.", "Tags: every mapped test carries `[PartA]` plus its ID tags (`/` -> `_`). Run one ID: `fohcore_tests \"[D-ERR]\"`.", "",
           "| ID | Test(s) | Status |", "|---|---|---|"] + [f"| {a} | {b} | {c} |" for a, b, c in rows]
    from collections import Counter
    c = Counter(r[2].split(" ")[0] for r in rows)
    out += ["", "Summary: " + ", ".join(f"{k}: {v}" for k, v in sorted(c.items()))]
    os.makedirs(os.path.join(ROOT, "docs/qa"), exist_ok=True)
    open(os.path.join(ROOT, "docs/qa/part-a-coverage.md"), "w").write("\n".join(out) + "\n"); print("\n".join(out[-1:]))
if __name__ == "__main__":
    tag() if sys.argv[1] == "tag" else doc(sys.argv[2:])
